-- Hive Partitioning
-- The partition based filters help limiting the inspection of the required files (aka "predicate pushdown").
-- 💡 Comment either the filter `AND year = 2023` or `AND month = 3` to see the predicate pushdown in action.
EXPLAIN ANALYZE
SELECT
    -- Projection pushdown will be used
    species,
    avg(body_mass_g) AS body_mass_g,
FROM read_parquet($parquet_file || '/**/*.parquet', hive_partitioning = true)
WHERE
    true
    -- Predicate pushdown will be used
    AND year = 2023
    AND month = 3
GROUP BY ALL;

