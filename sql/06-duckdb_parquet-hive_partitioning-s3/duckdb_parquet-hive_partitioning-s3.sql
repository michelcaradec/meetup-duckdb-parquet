-- Disable all caching for demonstration purpose
-- https://duckdb.org/docs/current/configuration/overview
SET enable_http_metadata_cache = false;
SET parquet_metadata_cache = false;
SET enable_external_file_cache = false;
SET disable_parquet_prefetching = true;

SET VARIABLE bucket = 's3://parquet-demo/';
SET VARIABLE parquet_file = $bucket || 'penguins';

SET VARIABLE key_id = getenv('S3_KEY_ID');
SET VARIABLE secret = getenv('S3_SECRET');

.mode trash

-- Create a secret for (Vault)S3
-- https://duckdb.org/docs/lts/core_extensions/httpfs/s3api
CREATE OR REPLACE TEMPORARY SECRET secret_s3 (
    TYPE s3,
    REGION 'us-east-1',
    -- If two secrets exist for a service type, the scope can be used to decide which one should be used.
    SCOPE $bucket,
    ENDPOINT 'localhost:9999',
    USE_SSL false,
    URL_STYLE 'path',
    -- Access key "parquet-demo"
    KEY_ID $key_id,
    SECRET $secret
);

.mode duckbox

-- View the created secret
FROM duckdb_secrets()
WHERE name = 'secret_s3';

-- Check that the secret will be used with the Parquet file on S3
FROM which_secret($parquet_file, 's3');

-- Parquet Generation
-- The CSV file was generated by the notebook "04-duckdb_parquet-metadata.ipynb"
COPY (
    FROM './data/penguins.csv'
    -- Order by body_mass to organize row groups
    ORDER BY body_mass_g
)
TO ($parquet_file) (
    FORMAT parquet,
    OVERWRITE true,
    -- The Parquet files will be organized by year and month
    PARTITION_BY (year, month),
    -- Some metadata to track the origin of the Parquet file
    KV_METADATA {
        purpose: 'demonstration',
        datasource: 'penguins.csv',
        code: 123_456,
    }
);

-- Parquet Files Size
SELECT round(SUM(file_size_bytes) / 1024, 2) AS parquet_total_size
FROM parquet_file_metadata($parquet_file || '/**/*.parquet');

-- Enable the "man in the middle" proxy to watch requests sent by DuckDB to the object storage service
SET http_proxy = getenv('S3_HTTP_PROXY');

